"""Bake the title card's lettering (port/src/intro_card.c) into port/src/intro_font.h.

  python3 port/tools/bake_intro_font.py [FONT.ttf]

Only the glyphs of the card's two lines are kept, each as a signed distance field: a small grid whose
bytes give the distance to the glyph's outline (128 = on the outline, more = inside), which the runtime
scales to any size with a smooth threshold, so the text stays sharp at any window resolution. Each line
also keeps its glyphs' pen positions as the font lays them out (advances and kerning).

The default font is Adwaita Sans (an Inter derivative, SIL Open Font License 1.1), a variable font: the
name is drawn at a light weight and display optical size, the "PORT BY" line at medium weight.
"""
import base64
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent.parent
FONT = "/usr/share/fonts/Adwaita/AdwaitaSans-Regular.ttf"
SS = 8  # supersampling of the outline render relative to the field

# (C name, text, field pixels per em, spread in field pixels, optical size, weight)
LINES = [
    ("intro_label", "PORT BY", 40, 5, 14, 500),
    ("intro_title", "CipherNovaa", 72, 10, 32, 300),
]


def edge_points(cov):
    """Sub-pixel points on the 50% coverage contour: between each pair of 4-neighbours on opposite sides."""
    pts = []
    for axis in (0, 1):
        a = cov[:-1, :] if axis == 0 else cov[:, :-1]
        b = cov[1:, :] if axis == 0 else cov[:, 1:]
        cross = (a >= 0.5) != (b >= 0.5)
        ys, xs = np.nonzero(cross)
        ca, cb = a[ys, xs], b[ys, xs]
        t = (0.5 - ca) / (cb - ca)
        if axis == 0:
            pts.append(np.stack([xs + 0.5, ys + 0.5 + t], 1))
        else:
            pts.append(np.stack([xs + 0.5 + t, ys + 0.5], 1))
    return np.concatenate(pts)


def glyph_field(font, ch, em, spread):
    """-> (w, h, left, top, bytes): the field's size and its top-left corner relative to the pen position on
    the baseline (field pixels, y down)."""
    hi = em * SS
    big = 2 * hi
    img = Image.new("L", (3 * hi, 3 * hi), 0)
    ImageDraw.Draw(img).text((hi, big), ch, font=font, fill=255, anchor="ls")
    cov = np.asarray(img, dtype=np.float64) / 255.0
    ys, xs = np.nonzero(cov > 0)
    # the field's cell, in field pixels relative to the pen (origin at (hi, big) in the render)
    left = int(np.floor((xs.min() - hi) / SS)) - spread - 1
    top = int(np.floor((ys.min() - big) / SS)) - spread - 1
    right = int(np.ceil((xs.max() + 1 - hi) / SS)) + spread + 1
    bottom = int(np.ceil((ys.max() + 1 - big) / SS)) + spread + 1
    w, h = right - left, bottom - top
    edges = edge_points(cov)
    gx, gy = np.meshgrid(np.arange(w), np.arange(h))
    px = (hi + (left + gx + 0.5) * SS).ravel()
    py = (big + (top + gy + 0.5) * SS).ravel()
    dist = np.empty(px.size)
    for i in range(0, px.size, 256):
        dx = px[i:i + 256, None] - edges[None, :, 0]
        dy = py[i:i + 256, None] - edges[None, :, 1]
        dist[i:i + 256] = np.sqrt((dx * dx + dy * dy).min(1))
    inside = cov[py.astype(int), px.astype(int)] >= 0.5
    d = np.where(inside, dist, -dist) / SS  # field pixels, positive inside
    v = np.clip(np.rint((0.5 + d / (2 * spread)) * 255), 0, 255).astype(np.uint8)
    return w, h, left, top, v.tobytes()


def main():
    font_path = sys.argv[1] if len(sys.argv) > 1 else FONT
    glyphs, blob, lines = [], bytearray(), []
    for name, text, em, spread, opsz, wght in LINES:
        font = ImageFont.truetype(font_path, em * SS)
        try:
            font.set_variation_by_axes([opsz, wght])
        except (OSError, ValueError):
            pass  # a static font: its own weight
        cache, idx, pens = {}, [], []
        for i, ch in enumerate(text):
            pen = (font.getlength(text[:i + 1]) - font.getlength(ch)) / (em * SS)
            if ch == " ":
                continue
            if ch not in cache:
                w, h, left, top, data = glyph_field(font, ch, em, spread)
                cache[ch] = len(glyphs)
                glyphs.append((ch, w, h, left, top, len(blob)))
                blob += data
            idx.append(cache[ch])
            pens.append(pen)
        ascent, descent = font.getmetrics()
        caps = -font.getbbox("H", anchor="ls")[1] / (em * SS)
        lines.append((name, text, em, spread, caps, font.getlength(text) / (em * SS), idx, pens))

    out = [
        "/* Generated by port/tools/bake_intro_font.py: signed distance fields of the title card's glyphs",
        " * (intro_card.c). Byte = 128 + distance to the outline (positive inside) * 127.5 / spread.",
        " *",
        f" * Glyphs from {Path(font_path).name}: Adwaita Sans, Copyright (c) 2016 The Inter Project Authors,",
        " * (c) 2015-2025 Renzhi Li, (c) 2025 Jamie Gravendeel, (c) 2025 Florian Muellner; licensed under the",
        " * SIL Open Font License, Version 1.1 (https://openfontlicense.org). */",
        "",
        "typedef struct {",
        "    unsigned short w, h; /* field size */",
        "    short left, top;     /* its top-left corner from the pen position on the baseline (y down) */",
        "    unsigned offset;     /* into the decoded intro_font_b64 */",
        "} IntroGlyph;",
        "",
        "typedef struct {",
        "    const char *text;",
        "    float em, spread;    /* field pixels per em; distance (field pixels) of bytes 0 and 255 */",
        "    float cap_height;    /* em */",
        "    float advance;       /* em */",
        "    int n;               /* glyphs drawn (spaces have none) */",
        "    unsigned char glyph[16];",
        "    float pen[16];       /* pen x of each, em, kerned */",
        "} IntroLine;",
        "",
        "static const IntroGlyph intro_glyphs[] = {",
    ]
    for ch, w, h, left, top, off in glyphs:
        out.append(f"    {{{w}, {h}, {left}, {top}, {off}}}, /* {ch} */")
    out.append("};")
    out.append("")
    for name, text, em, spread, caps, adv, idx, pens in lines:
        out.append(f"static const IntroLine {name} = {{\"{text}\", {em}, {spread}, {caps:.4f}f, {adv:.4f}f, "
                   f"{len(idx)},")
        out.append("    {" + ", ".join(map(str, idx)) + "},")
        out.append("    {" + ", ".join(f"{p:.4f}f" for p in pens) + "}};")
        out.append("")
    b64 = base64.b64encode(bytes(blob)).decode()
    out.append(f"#define INTRO_FONT_BYTES {len(blob)}")
    out.append("static const char intro_font_b64[] =")
    for i in range(0, len(b64), 110):
        out.append(f"    \"{b64[i:i + 110]}\"" + (";" if i + 110 >= len(b64) else ""))
    path = ROOT / "port/src/intro_font.h"
    path.write_text("\n".join(out) + "\n")
    print(f"{path}: {len(glyphs)} glyphs, {len(blob)} bytes of fields, {path.stat().st_size} bytes of source")


if __name__ == "__main__":
    main()
