"""The Windows build's linker script (port/Makefile, make windows): MinGW's own, with two changes.

  win_link.py CC OUT OBJS...

- PS1 memory's low addresses: the PS1 sees its RAM at 0x00000000 too (KUSEG), which the Linux build maps there (main.c)
  but Windows has taken by then (the process heap, the main thread's stack). The image is based at 0x00010000 and
  its first section (.kuseg) holds the addresses up to 0x00800000, so nothing else is put there: platform_win.c makes
  it inaccessible, and an access there is moved onto the KSEG0 mirror at 0x80000000 as on Linux below 64 KB (main.c
  on_segv; recompiled code's loads and stores do it themselves, recomp.h RA).
- Names: the objects are compiled without the leading underscore of C names on 32-bit Windows (-fno-leading-underscore),
  so they have the Linux build's names; each name they use that none of them defines is bridged to the C runtime's,
  Windows' and SDL's (PROVIDE(name = _name), __imp_name = __imp__name; EXTERN for the libraries' member to be
  linked in), and the C runtime's start-up finds main and WinMain.
"""
import subprocess
import sys

KUSEG_END = 0x00800000  # (the image's base, 0x00010000, is port/Makefile's --image-base)
# names the script itself defines (or the linker does)
LINKER = {"etext", "_etext", "__executable_start", "__kuseg_start__", "__image_base__", "__ImageBase"}


def default_script(cc):
    out = subprocess.run([cc, "-Wl,--verbose", "-nostdlib", "-o", "/dev/null", "-x", "c", "/dev/null"],
                         capture_output=True, text=True).stdout
    lines = out.splitlines()
    marks = [i for i, l in enumerate(lines) if l.startswith("=" * 20)]
    if len(marks) < 2:
        sys.exit("win_link.py: no default linker script from " + cc)
    return "\n".join(lines[marks[0] + 1:marks[1]])


def symbols(objs):
    out = subprocess.run(["nm", *objs], capture_output=True, text=True, check=True).stdout
    defined, undefined = set(), set()
    for l in out.splitlines():
        f = l.split()
        if len(f) == 3 and f[1] not in "Uw":
            defined.add(f[2])
        elif len(f) == 2 and f[0] == "U":  # (weak ones nothing defines stay 0, as on Linux)
            undefined.add(f[1])
    return defined, undefined


def main():
    cc, out, objs = sys.argv[1], sys.argv[2], sys.argv[3:]
    script = default_script(cc)
    text = "  .text  __image_base__ + ( __section_alignment__ < 0x1000 ? . : __section_alignment__ ) :"
    if text not in script:
        sys.exit("win_link.py: MinGW's linker script has changed (its .text line)")
    script = script.replace(text, (
        "  /* PS1 KUSEG: platform_win.c makes it inaccessible (port/tools/win_link.py) */\n"
        "  .kuseg __image_base__ + 0x1000 :\n"
        "  {\n"
        "    __kuseg_start__ = . ;\n"
        "    . = 0x%X - (__image_base__ + 0x1000) ;\n"
        "  }\n"
        "  .text BLOCK(__section_alignment__) :") % KUSEG_END, 1)
    script = script.replace("    KEEP (*(SORT_NONE(.init)))", "    __executable_start = . ;\n    KEEP (*(SORT_NONE(.init)))", 1)
    defined, undefined = symbols(objs)
    bridge = []
    for name in sorted(undefined - defined - LINKER):
        target = "__imp__" + name[6:] if name.startswith("__imp_") else "_" + name
        bridge.append('EXTERN("%s") PROVIDE("%s" = "%s");' % (target, name, target))
    bridge.append('PROVIDE("_main" = "main");')
    bridge.append('PROVIDE("_WinMain@16" = "WinMain@16");')
    with open(out, "w") as f:
        f.write("/* Generated by port/tools/win_link.py */\n" + script + "\n/* names bridged to the libraries' */\n"
                + "\n".join(bridge) + "\n")


if __name__ == "__main__":
    main()
